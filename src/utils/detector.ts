// AI Detection engine - analyzes text for patterns common in AI-generated content

interface DetectionResult {
  score: number; // 0-100, higher = more likely AI
  classification: 'human' | 'mixed' | 'ai-generated';
  signals: DetectionSignal[];
}

interface DetectionSignal {
  type: 'perplexity' | 'burstiness' | 'patterns' | 'vocabulary' | 'structure';
  label: string;
  severity: 'low' | 'medium' | 'high';
  detail: string;
}

// Common AI-generated patterns
const aiPatterns = {
  formalTransitions: [
    'Furthermore', 'Moreover', 'Additionally', 'Consequently',
    'Nevertheless', 'In conclusion', 'It is important to note',
    'It is worth mentioning', 'In today\'s world', 'In the realm of',
  ],
  aiVocabulary: [
    'delve', 'utilize', 'facilitate', 'leverage', 'comprehensive',
    'fundamental', 'robust', 'seamless', 'innovative', 'paradigm',
    'holistic', 'synergy', 'streamline', 'multifaceted', 'nuanced',
    'tapestry', 'landscape', 'ecosystem', 'spearhead', 'myriad',
    'plethora', 'foster', 'empower', 'cultivate', 'harness',
  ],
  aiStructures: [
    /Not only .+ but also/g,
    /It is .+ that/g,
    /The (?:ability|capacity|potential) to .+ (?:is|represents)/g,
    /In (?:today's|the modern|this digital) (?:world|era|age)/g,
    /As .+ continues to .+, (?:it|the|this)/g,
    /plays? a (?:crucial|vital|pivotal|essential|key) role/g,
    /This (?:is|represents) a (?:testament|reflection|indication)/g,
  ],
  aiSentencePatterns: [
    /^[A-Z][^.!?]+\. [A-Z][^.!?]+\. [A-Z][^.!?]+\./m, // Very uniform sentence lengths
  ]
};

function calculatePerplexity(text: string): number {
  const words = text.toLowerCase().split(/\s+/);
  const uniqueWords = new Set(words);
  const lexicalDiversity = uniqueWords.size / words.length;
  
  // AI text tends to have moderate lexical diversity (not too random, not too repetitive)
  // Human text tends to be more varied
  const score = Math.abs(0.6 - lexicalDiversity) * 100;
  return Math.min(100, score);
}

function calculateBurstiness(text: string): number {
  const sentences = text.split(/[.!?]+/).filter(s => s.trim().length > 0);
  if (sentences.length < 3) return 50;
  
  const lengths = sentences.map(s => s.trim().split(/\s+/).length);
  const mean = lengths.reduce((a, b) => a + b, 0) / lengths.length;
  const variance = lengths.reduce((sum, l) => sum + Math.pow(l - mean, 2), 0) / lengths.length;
  const stdDev = Math.sqrt(variance);
  const coefficientOfVariation = stdDev / mean;
  
  // AI text has low burstiness (uniform sentence lengths)
  // Human text has high burstiness (varied sentence lengths)
  // Low CV = more AI-like
  const score = Math.max(0, 100 - coefficientOfVariation * 150);
  return Math.min(100, score);
}

function detectPatterns(text: string): DetectionSignal[] {
  const signals: DetectionSignal[] = [];
  const lowerText = text.toLowerCase();
  
  // Check for formal transitions
  const transitionCount = aiPatterns.formalTransitions.filter(t => 
    text.includes(t) || lowerText.includes(t.toLowerCase())
  ).length;
  
  if (transitionCount >= 3) {
    signals.push({
      type: 'patterns',
      label: 'Formulaic Transitions',
      severity: 'high',
      detail: `Found ${transitionCount} formal transition phrases typical of AI writing`,
    });
  } else if (transitionCount >= 1) {
    signals.push({
      type: 'patterns',
      label: 'Formal Transitions',
      severity: 'medium',
      detail: `Found ${transitionCount} transition phrases that may indicate AI generation`,
    });
  }
  
  // Check for AI vocabulary
  const vocabCount = aiPatterns.aiVocabulary.filter(v => 
    lowerText.includes(v.toLowerCase())
  ).length;
  
  if (vocabCount >= 4) {
    signals.push({
      type: 'vocabulary',
      label: 'AI-Typical Vocabulary',
      severity: 'high',
      detail: `Detected ${vocabCount} words/phrases commonly overused in AI-generated text`,
    });
  } else if (vocabCount >= 2) {
    signals.push({
      type: 'vocabulary',
      label: 'Suspicious Vocabulary',
      severity: 'medium',
      detail: `Found ${vocabCount} words that are frequently used in AI content`,
    });
  }
  
  // Check for structural patterns
  const structuralMatches = aiPatterns.aiStructures.filter(p => p.test(text)).length;
  
  if (structuralMatches >= 2) {
    signals.push({
      type: 'structure',
      label: 'AI Sentence Patterns',
      severity: 'high',
      detail: `Detected ${structuralMatches} sentence structures commonly generated by AI models`,
    });
  } else if (structuralMatches >= 1) {
    signals.push({
      type: 'structure',
      label: 'Patterned Sentences',
      severity: 'low',
      detail: `Found ${structuralMatches} structural pattern that appears in AI writing`,
    });
  }
  
  return signals;
}

export function detectAI(text: string): DetectionResult {
  if (!text.trim() || text.split(/\s+/).length < 20) {
    return {
      score: 0,
      classification: 'human',
      signals: [],
    };
  }
  
  const perplexityScore = calculatePerplexity(text);
  const burstinessScore = calculateBurstiness(text);
  const patternSignals = detectPatterns(text);
  
  // Calculate word-level analysis
  const words = text.split(/\s+/);
  const avgWordLength = words.reduce((sum, w) => sum + w.replace(/[^a-zA-Z]/g, '').length, 0) / words.length;
  
  // AI text tends to have longer average word length
  const wordLengthScore = avgWordLength > 5.5 ? 30 : avgWordLength > 4.5 ? 15 : 0;
  
  // Check for contractions (humans use more)
  const contractionCount = (text.match(/\b\w+'\w+\b/g) || []).length;
  const contractionScore = contractionCount === 0 ? 20 : contractionCount < 3 ? 10 : 0;
  
  // Paragraph uniformity check
  const paragraphs = text.split(/\n\n+/).filter(p => p.trim().length > 0);
  let paragraphScore = 0;
  if (paragraphs.length >= 3) {
    const paraLengths = paragraphs.map(p => p.length);
    const paraMean = paraLengths.reduce((a, b) => a + b, 0) / paraLengths.length;
    const paraVariance = paraLengths.reduce((sum, l) => sum + Math.pow(l - paraMean, 2), 0) / paraLengths.length;
    const paraCV = Math.sqrt(paraVariance) / paraMean;
    paragraphScore = paraCV < 0.3 ? 25 : paraCV < 0.5 ? 10 : 0;
  }
  
  // Calculate final score (weighted average)
  const patternScore = patternSignals.reduce((sum, s) => {
    return sum + (s.severity === 'high' ? 25 : s.severity === 'medium' ? 15 : 8);
  }, 0);
  
  const finalScore = Math.min(100, Math.round(
    perplexityScore * 0.2 +
    burstinessScore * 0.25 +
    Math.min(patternScore, 40) * 0.25 +
    wordLengthScore * 0.1 +
    contractionScore * 0.1 +
    paragraphScore * 0.1
  ));
  
  // Add perplexity and burstiness signals
  const allSignals: DetectionSignal[] = [...patternSignals];
  
  if (burstinessScore > 60) {
    allSignals.push({
      type: 'burstiness',
      label: 'Low Burstiness',
      severity: burstinessScore > 75 ? 'high' : 'medium',
      detail: 'Sentence lengths are unusually uniform — humans typically vary them more',
    });
  }
  
  if (perplexityScore > 55) {
    allSignals.push({
      type: 'perplexity',
      label: 'Low Perplexity',
      severity: perplexityScore > 70 ? 'high' : 'medium',
      detail: 'Word choices are too predictable — human writing tends to be more surprising',
    });
  }
  
  let classification: 'human' | 'mixed' | 'ai-generated';
  if (finalScore >= 65) classification = 'ai-generated';
  else if (finalScore >= 35) classification = 'mixed';
  else classification = 'human';
  
  return {
    score: finalScore,
    classification,
    signals: allSignals,
  };
}
